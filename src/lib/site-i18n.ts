export type SiteKey = keyof typeof DICT;

/** Translate a UI string. `{name}` placeholders are filled from `vars`. */
export function t(locale: Locale, key: SiteKey, vars?: Record<string, string | number>): string {
  let s: string = DICT[key][locale] ?? DICT[key].en;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** "1 unit · 3 lessons" in the right language. */
export function unitsLessons(locale: Locale, units: number, lessons: number) {
  return t(locale, "unitsLessons", {
    u: units,
    l: lessons,
    units: t(locale, units === 1 ? "unit1" : "unitN"),
    lessons: t(locale, lessons === 1 ? "lesson1" : "lessonN"),
  });
}
